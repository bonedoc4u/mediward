CREATE OR REPLACE FUNCTION "public"."get_my_hospital_id"() RETURNS "uuid"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_hospital_id UUID;
  v_viewing     TEXT;
BEGIN
  BEGIN
    v_viewing := current_setting('app.viewing_hospital_id', true);
  EXCEPTION WHEN OTHERS THEN
    v_viewing := NULL;
  END;

  -- Only superadmin may activate the cross-tenant viewing override.
  IF v_viewing IS NOT NULL AND v_viewing != '' AND public.is_superadmin() THEN
    RETURN v_viewing::UUID;
  END IF;

  SELECT hospital_id INTO v_hospital_id
  FROM public.app_users
  WHERE id = auth.uid();

  RETURN v_hospital_id;
END;
$$;


