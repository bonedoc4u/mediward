CREATE OR REPLACE FUNCTION "public"."archive_discharged_patients"("days_old" integer DEFAULT 30) RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  archived_count int;
BEGIN
  -- Only superadmin may call this function
  IF NOT public.is_superadmin() THEN
    RAISE EXCEPTION 'Permission denied: superadmin required (code: E_ARCHIVE_FORBIDDEN)';
  END IF;

  UPDATE public.patients
  SET archived_at = now()
  WHERE patient_status = 'Discharged'
    AND archived_at IS NULL
    AND COALESCE(dod::date, created_at::date) < (now() - make_interval(days => days_old));

  GET DIAGNOSTICS archived_count = ROW_COUNT;
  RETURN archived_count;
END;
$$;


