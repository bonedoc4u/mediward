-- ----------------------------------------------------------------------------
-- Hand-written prelude (the only one): build with production's grants.
--
-- A new Supabase database grants ALL on every new table, function and
-- sequence in "public" to anon and authenticated by default. Production
-- revoked many of those, but a dump only lists the grants that exist, not
-- the ones that were taken away. Without this prelude a rebuilt database
-- would let signed-out callers execute functions such as erase_patient_data
-- and hold table rights production does not give them (found by rebuilding
-- this file locally and comparing with production, 14 Nov 2026).
--
-- So: stop the automatic grants while the objects below are created; the
-- explicit GRANTs from production then apply exactly. The dump's own
-- ALTER DEFAULT PRIVILEGES lines at the end put the defaults back as
-- production has them, for migrations after this one.
-- ----------------------------------------------------------------------------
