CREATE OR REPLACE FUNCTION "public"."enforce_patient_role_rules"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
DECLARE
  -- Columns the database itself maintains on every update; never a user's change.
  c_bookkeeping constant text[] := ARRAY['updated_at', 'version'];
  -- Columns that hold a patient's orders (ORDER_COLUMNS in utils/permissions.ts).
  c_order_columns constant text[] := ARRAY['todos'];
BEGIN
  -- Not a signed-in user: service role, scheduled job, SQL editor. Those are
  -- not subject to RLS either. (The anon key cannot reach here with a write:
  -- no policy on patients applies to it.)
  IF auth.uid() IS NULL THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NOT public.current_user_can('patient:add') THEN
      RAISE EXCEPTION 'ROLE_FORBIDDEN: your role cannot add a patient'
        USING ERRCODE = '42501';
    END IF;
    IF NEW.patient_status = 'Discharged' AND NOT public.current_user_can('patient:discharge') THEN
      RAISE EXCEPTION 'ROLE_FORBIDDEN: your role cannot discharge a patient'
        USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
  END IF;

  -- UPDATE, rule 1: without patient:edit, only the orders may change — and
  -- only for a role that may write rounds. Everything else must be identical.
  -- A column added later is locked for such a role by default.
  IF NOT public.current_user_can('patient:edit') THEN
    IF NOT public.current_user_can('rounds:write') THEN
      RAISE EXCEPTION 'ROLE_FORBIDDEN: your role cannot change a patient record'
        USING ERRCODE = '42501';
    END IF;
    IF (to_jsonb(NEW) - c_bookkeeping - c_order_columns)
       IS DISTINCT FROM (to_jsonb(OLD) - c_bookkeeping - c_order_columns) THEN
      RAISE EXCEPTION 'ROLE_FORBIDDEN: your role can change a patient''s orders only'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  -- UPDATE, rule 2: a discharge, or undoing one, needs patient:discharge.
  IF NEW.patient_status IS DISTINCT FROM OLD.patient_status
     AND 'Discharged' IN (COALESCE(OLD.patient_status, ''), COALESCE(NEW.patient_status, ''))
     AND NOT public.current_user_can('patient:discharge') THEN
    RAISE EXCEPTION 'ROLE_FORBIDDEN: your role cannot discharge a patient or undo a discharge'
      USING ERRCODE = '42501';
  END IF;

  -- UPDATE, rule 3: removing a record (deleted_at), or restoring it, needs patient:delete.
  IF NEW.deleted_at IS DISTINCT FROM OLD.deleted_at
     AND NOT public.current_user_can('patient:delete') THEN
    RAISE EXCEPTION 'ROLE_FORBIDDEN: your role cannot remove or restore a patient record'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."enforce_patient_role_rules"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."enforce_role_permission"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_allowed boolean := false;
  v_needs   text := '';
BEGIN
  -- Not a signed-in user (service role, scheduled job, SQL editor), or a
  -- change the database makes itself while carrying out another change (a
  -- foreign-key cascade; see step 3). Neither is restricted here.
  IF auth.uid() IS NULL OR pg_trigger_depth() > 1 THEN
    RETURN NULL;
  END IF;

  -- The trigger's arguments are permissions. Having ANY one of them is enough.
  FOR i IN 0 .. TG_NARGS - 1 LOOP
    v_allowed := v_allowed OR public.current_user_can(TG_ARGV[i]);
    v_needs   := v_needs || CASE WHEN i > 0 THEN ' or ' ELSE '' END || TG_ARGV[i];
  END LOOP;

  IF NOT v_allowed THEN
    RAISE EXCEPTION 'ROLE_FORBIDDEN: your role cannot change % (needs %)', TG_TABLE_NAME, v_needs
      USING ERRCODE = '42501';
  END IF;

  RETURN NULL;
END;
$$;


ALTER FUNCTION "public"."enforce_role_permission"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."erase_patient_data"("p_ip_no" "text", "p_dry_run" boolean DEFAULT false) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $_$
DECLARE
  -- Columns of the patient row that stay exactly as they are.
  c_keep constant text[] := ARRAY[
    'ip_no', 'hospital_id', 'ward', 'unit', 'doa', 'dod', 'gender',
    'patient_status', 'pac_status', 'specialty',
    'created_at', 'updated_at', 'version', 'deleted_at', 'archived_at'
  ];
  -- Required columns with no default: they get a fixed, empty-looking value.
  c_fixed constant text[] := ARRAY['name', 'age', 'bed', 'diagnosis'];
  -- A current inpatient. Erasing their chart mid-admission would be unsafe.
  c_inpatient constant text[] := ARRAY['Fit', 'Review', 'Critical', 'Discharge Ready'];

  v_uid      uuid := auth.uid();
  v_patient  public.patients%ROWTYPE;
  v_removed  jsonb := '{}'::jsonb;
  v_total    bigint := 0;
  v_n        bigint;
  v_set      text;
  v_where    text;
  v_user     text;
  v_images   jsonb := '[]'::jsonb;
  r          record;
BEGIN
  -- ── 1. Checks ────────────────────────────────────────────────────────────
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'ROLE_FORBIDDEN: sign in to erase patient data' USING ERRCODE = '42501';
  END IF;
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'ROLE_FORBIDDEN: only an admin can erase patient data' USING ERRCODE = '42501';
  END IF;

  -- Locks the row until the function ends, so nothing is saved in between.
  SELECT * INTO v_patient
  FROM public.patients
  WHERE ip_no = btrim(p_ip_no)
    AND (hospital_id = public.get_my_hospital_id() OR public.is_superadmin())
  FOR UPDATE;

  IF NOT FOUND THEN
    -- P0001, not P0002: the API answers P0001 with "400 bad request" and
    -- P0002 with "500 server error", which would look like a crash.
    RAISE EXCEPTION 'PATIENT_NOT_FOUND: no patient with IP number % in this hospital', btrim(p_ip_no)
      USING ERRCODE = 'P0001';
  END IF;

  IF v_patient.deleted_at IS NULL AND v_patient.patient_status = ANY (c_inpatient) THEN
    RAISE EXCEPTION 'PATIENT_STILL_ADMITTED: % is a current inpatient (status %). Discharge the patient first.',
      v_patient.ip_no, v_patient.patient_status
      USING ERRCODE = 'P0001';
  END IF;

  -- Image files that belong to the patient (for the app to remove from
  -- storage): the imaging table, and the old in-row list some records have.
  IF to_regclass('public.imaging') IS NOT NULL THEN
    SELECT COALESCE(jsonb_agg(DISTINCT i.image_url), '[]'::jsonb) INTO v_images
    FROM public.imaging i
    WHERE i.patient_ip_no = v_patient.ip_no AND COALESCE(i.image_url, '') <> '';
  END IF;
  IF jsonb_typeof(v_patient.investigations) = 'array' THEN
    SELECT v_images || COALESCE(jsonb_agg(DISTINCT u.url), '[]'::jsonb) INTO v_images
    FROM (
      SELECT COALESCE(e ->> 'imageUrl', e ->> 'image_url') AS url
      FROM jsonb_array_elements(v_patient.investigations) AS e
    ) u
    WHERE COALESCE(u.url, '') <> '';
  END IF;

  -- ── 2. Linked rows ───────────────────────────────────────────────────────
  FOR r IN
    SELECT c.relname AS tbl,
           a.attname AS col,
           EXISTS (
             SELECT 1 FROM pg_constraint k
             WHERE k.contype = 'f' AND k.conrelid = c.oid
               AND k.confrelid = 'public.patients'::regclass
               AND a.attnum = ANY (k.conkey)
           ) AS has_fk,
           EXISTS (
             SELECT 1 FROM pg_attribute h
             WHERE h.attrelid = c.oid AND h.attname = 'hospital_id' AND NOT h.attisdropped
           ) AS has_hospital
    FROM pg_attribute a
    JOIN pg_class c     ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'r'
      AND c.relname <> 'patients'
      AND a.attnum > 0 AND NOT a.attisdropped
      AND (
        a.attname = 'patient_ip_no'
        OR EXISTS (
          SELECT 1 FROM pg_constraint k
          WHERE k.contype = 'f' AND k.conrelid = c.oid
            AND k.confrelid = 'public.patients'::regclass
            AND a.attnum = ANY (k.conkey)
        )
      )
    ORDER BY c.relname, a.attname
  LOOP
    -- With a foreign key the database guarantees the row belongs to this
    -- patient. Without one (a plain text column) stay inside the hospital.
    v_where := format('%I = $1', r.col)
      || CASE WHEN r.has_fk OR NOT r.has_hospital THEN '' ELSE ' AND hospital_id = $2' END;
    IF p_dry_run THEN
      EXECUTE format('SELECT count(*) FROM public.%I WHERE %s', r.tbl, v_where)
        INTO v_n USING v_patient.ip_no, v_patient.hospital_id;
    ELSE
      EXECUTE format('WITH gone AS (DELETE FROM public.%I WHERE %s RETURNING 1) SELECT count(*) FROM gone', r.tbl, v_where)
        INTO v_n USING v_patient.ip_no, v_patient.hospital_id;
    END IF;
    v_removed := v_removed || jsonb_build_object(r.tbl, COALESCE((v_removed ->> r.tbl)::bigint, 0) + v_n);
    v_total := v_total + v_n;
  END LOOP;

  IF p_dry_run THEN
    RETURN jsonb_build_object(
      'dry_run', true,
      'ip_no', v_patient.ip_no,
      'hospital_id', v_patient.hospital_id,
      'name', v_patient.name,
      'age', v_patient.age,
      'gender', v_patient.gender,
      'ward', v_patient.ward,
      'bed', v_patient.bed,
      'unit', v_patient.unit,
      'patient_status', v_patient.patient_status,
      'rows_to_remove', v_total,
      'image_urls', v_images
    );
  END IF;

  -- ── 3. The patient row ───────────────────────────────────────────────────
  -- Every column that is not kept and not fixed goes back to its default
  -- (NULL where it has none). A new required column without a default makes
  -- this fail loudly instead of leaving data behind.
  SELECT string_agg(format('%I = DEFAULT', a.attname), ', ' ORDER BY a.attnum)
  INTO v_set
  FROM pg_attribute a
  WHERE a.attrelid = 'public.patients'::regclass
    AND a.attnum > 0 AND NOT a.attisdropped AND a.attgenerated = ''
    AND a.attname <> ALL (c_keep || c_fixed);

  EXECUTE 'UPDATE public.patients SET name = $1, age = 0, bed = $2, diagnosis = $3'
       || COALESCE(', ' || v_set, '')
       || ' WHERE ip_no = $4'
    USING '[REDACTED]', '', 'Personal data erased on request', v_patient.ip_no;

  -- ── 4. Audit entry ───────────────────────────────────────────────────────
  SELECT name INTO v_user FROM public.app_users WHERE id = v_uid;
  INSERT INTO public.audit_log (user_id, user_name, hospital_id, action, entity, entity_id, details)
  VALUES (
    v_uid::text, COALESCE(v_user, 'Unknown'), v_patient.hospital_id,
    'DELETE', 'patient', v_patient.ip_no,
    format('Personal data erased on request (DPDP s.13). Linked rows removed: %s.', v_total)
  );

  -- ── 5. Report ────────────────────────────────────────────────────────────
  RETURN jsonb_build_object(
    'ip_no', v_patient.ip_no,
    'erased_at', now(),
    'rows_removed', v_total,
    'removed', v_removed
  );
END;
$_$;


