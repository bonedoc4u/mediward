CREATE OR REPLACE FUNCTION "public"."validate_pac_flow"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_flow      JSONB := NEW.pac_flow;
  v_branch    JSONB;
  v_all_done  BOOLEAN := TRUE;
  v_has_branches BOOLEAN;
BEGIN
  IF v_flow IS NULL THEN RETURN NEW; END IF;

  IF NOT (v_flow->>'seenByAnaesthesia')::boolean THEN
    RETURN NEW;
  END IF;

  v_has_branches := jsonb_array_length(v_flow->'branches') > 0;

  IF NOT v_has_branches THEN
    -- Seen but no branches yet → pending
    IF NEW.pac_status = 'PAC Fit' THEN
      NEW.pac_status := 'PAC Pending';
    END IF;
    RETURN NEW;
  END IF;

  FOR v_branch IN SELECT * FROM jsonb_array_elements(v_flow->'branches') LOOP
    IF NOT (v_branch->>'isDone')::boolean THEN
      v_all_done := FALSE;
      EXIT;
    END IF;
  END LOOP;

  IF v_all_done THEN
    NEW.pac_status := 'PAC Fit';
  ELSIF NEW.pac_status = 'PAC Fit' THEN
    NEW.pac_status := 'PAC Pending';
  END IF;

  RETURN NEW;
END;
$$;


